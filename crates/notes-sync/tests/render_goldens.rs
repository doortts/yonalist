//! The spec's grammar is the renderer's output, byte for byte. Each fixture is
//! the file a stated document state has to produce; if the renderer and the
//! spec ever disagree, one of them is wrong and this says so.

use notes_sync::document::{
    DocumentId, DocumentNode, DocumentRoot, ImageReference, Marker, NodeBody, PageDocument,
    TrashDocument, VaultFile,
};
use notes_sync::render::render;

/// A golden, compared — or rewritten, when a change to the format is the point.
///
/// `UPDATE_FIXTURES=1 cargo test -p notes-sync --test render_goldens` writes what
/// the renderer produces into the four fixtures and passes. Nothing else in the
/// suite changes behaviour, and a run without the variable is the ordinary
/// byte-for-byte comparison — so a fixture can only move when somebody asked for
/// it to, in a diff they then have to read.
///
/// This exists because the alternative is what happened twice already: a format
/// change lands, four fixtures disagree, and they get regenerated by hand from a
/// throwaway test written for the occasion and deleted afterwards. The next
/// change re-invents it. A snapshot library would also do this, but these files
/// are the spec's own goldens — `docs/v2/sync-spec.md` §11 points at them — and
/// they are worth keeping as readable Markdown under their own names rather than
/// moving into a tool's store.
fn golden(name: &str, rendered: Vec<u8>, committed: &str) {
    let rendered = String::from_utf8(rendered).expect("utf-8");
    if std::env::var_os("UPDATE_FIXTURES").is_some() {
        std::fs::write(format!("fixtures/{name}.md"), &rendered).expect("write the fixture");
        return;
    }
    assert_eq!(
        rendered, committed,
        "`{name}.md` no longer matches the renderer. If the format was meant to \
         change, rerun with UPDATE_FIXTURES=1 and read the diff."
    );
}

fn node(id: &str, hlc: &str, text: &str) -> DocumentNode {
    DocumentNode {
        id: id.to_owned(),
        hlc: hlc.to_owned(),
        body: NodeBody::Text(text.to_owned()),
        note: String::new(),
        marker: Marker::Bullet,
        collapsed: false,
        completed: false,
        starred: false,
        from: None,
        place: None,
        unknown_tokens: Vec::new(),
        children: Vec::new(),
    }
}

fn page() -> PageDocument {
    let mut architecture = node("Nd0000000001", "0swkd7qz6-00-a3f2", "아키텍처 다시 그리기");
    let mut boundaries = node("Nd0000000002", "0swkd7qz7-00-a3f2", "크레이트 경계 정리");
    boundaries.marker = Marker::Todo;
    let mut diagram = node("Nd0000000003", "0swkd7qz8-00-a3f2", "");
    diagram.body = NodeBody::Image(ImageReference {
        original_name: "아키텍처.png".to_owned(),
        path: "assets/아키텍처-9f3a1c8e2044.png".to_owned(),
        display_width: 320,
        pixel_width: 1280,
        pixel_height: 720,
        byte_size: 421_904,
    });
    architecture.children = vec![boundaries, diagram];

    let mut tidied = node("Nd0000000004", "0swkd7qz9-00-a3f2", "정리한 것");
    tidied.completed = true;
    tidied.collapsed = true;

    PageDocument {
        id: DocumentId::Node("PrJects00001".to_owned()),
        parent: None,
        sort_key: None,
        max_hlc: "0swkd7qz9-00-a3f2".to_owned(),
        // Built in memory, so there is no file that could have been cut short.
        stated_max_hlc: "0swkd7qz9-00-a3f2".to_owned(),
        root: DocumentRoot {
            title: "Projects".to_owned(),
            note: "이번 분기에 손대는 것만.".to_owned(),
            hlc: "0swkd7qz5-00-a3f2".to_owned(),
            starred: true,
            ..DocumentRoot::default()
        },
        nodes: vec![architecture, tidied],
        unknown_frontmatter: Vec::new(),
    }
}

#[test]
fn a_page_renders_byte_identical_to_its_golden() {
    let rendered = render(&VaultFile::Page(page())).expect("render");

    golden("page", rendered, include_str!("../fixtures/page.md"));
}

#[test]
fn rendering_the_same_state_twice_is_byte_identical() {
    let first = render(&VaultFile::Page(page())).expect("render");
    let second = render(&VaultFile::Page(page())).expect("render");

    assert_eq!(first, second);
}

