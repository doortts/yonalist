/// A1. Punctuation reaches the file as the person typed it. A backslash in front
/// of every full stop and slash is what made these files unpleasant to read and
/// worse to edit — a reader has to mentally strip them, and anyone who fixes a
/// typo by hand has to know to put them back.
///
/// What still earns a backslash is a character that would open a block where it
/// sits, and that is a question about position rather than about the character.
#[test]
fn ordinary_punctuation_reaches_the_file_unescaped() {
    let mut plain = node(
        "Nd0000000001",
        "0swkd7qz6-00-a3f2",
        "Shift+Enter — 설명 입력하기. 자세히는 docs/v2/sync-spec.md 참고 (2026).",
    );
    plain.note = "값이 3.5 이상, 또는 a*b 꼴이면 skip_this_one 처리".to_owned();

    let (body, _) = rendered_parts(vec![plain]);

    assert_eq!(
        body[0],
        "- Shift+Enter — 설명 입력하기. 자세히는 docs/v2/sync-spec.md 참고 (2026). \
         <!-- yid: Nd0000000001 -->"
    );
    assert_eq!(
        body[1], "  > 값이 3.5 이상, 또는 a*b 꼴이면 skip_this_one 처리",
        "a note is prose, and prose is what a reader came for"
    );
}

/// The characters that keep their backslash, and why each one keeps it. Every
/// one of these is a shape this format's own parser would read as something
/// other than text if it were left alone.
#[test]
fn only_what_would_open_a_block_keeps_its_backslash() {
    let cases = [
        (
            "- 나열",
            r"\- 나열",
            "a line starting with a bullet marker is a bullet",
        ),
        (
            "![링크",
            r"\![링크",
            "and one starting with an image is an image",
        ),
        ("# 제목", r"\# 제목", "a heading marker opens a heading"),
        (
            "1. 첫째",
            r"1\. 첫째",
            "so does a number that closes into a list marker",
        ),
        (
            "1.5배",
            "1.5배",
            "but a number that closes into nothing is a number",
        ),
        ("-5도", "-5도", "and a minus that opens nothing is a minus"),
    ];

    for (typed, expected, why) in cases {
        let (body, _) = rendered_parts(vec![node("Nd0000000001", "0swkd7qz6-00-a3f2", typed)]);

        assert_eq!(
            body[0]
                .strip_prefix("- ")
                .expect("a bullet")
                .split(" <!--")
                .next()
                .expect("text"),
            expected,
            "{why}"
        );
    }
}

/// The body lines and the footer entries, apart. A test about *where* a fact is
/// written needs both halves, and the halves are what the format now separates.
fn rendered_parts(nodes: Vec<DocumentNode>) -> (Vec<String>, Vec<String>) {
    let mut document = page();
    document.root.note = String::new();
    document.nodes = nodes;
    let rendered =
        String::from_utf8(render(&VaultFile::Page(document)).expect("render")).expect("utf-8");
    let (body, footer) = rendered
        .split_once("\n\n")
        .expect("body")
        .1
        .split_once("<!-- yonalist\n")
        .expect("footer");
    (
        body.lines()
            .filter(|line| !line.is_empty())
            .map(str::to_owned)
            .collect(),
        footer
            .trim_end()
            .strip_suffix("-->")
            .expect("a closed footer")
            .lines()
            .map(str::to_owned)
            .collect(),
    )
}

/// A2. The body carries one thing per line: which block the line is. Everything
/// the sync needs in order to merge — the stamp, the place claim, the states
/// Markdown has no notation for, a picture's dimensions — moves to one block at
/// the end of the file, where a reader who came for the notes never has to look.
#[test]
fn a_body_line_carries_its_block_id_and_nothing_else() {
    for (name, bytes) in [
        ("page", include_str!("../fixtures/page.md")),
        ("home", include_str!("../fixtures/home.md")),
        ("split", include_str!("../fixtures/split.md")),
        ("trash", include_str!("../fixtures/trash.md")),
    ] {
        let (body, footer) = bytes
            .split_once("\n<!-- yonalist\n")
            .unwrap_or_else(|| panic!("{name} has no footer"));

        for line in body.lines() {
            let Some((_, comment)) = line.split_once("<!--") else {
                continue;
            };
            assert!(
                comment.starts_with(" yid: ") && comment.ends_with(" -->"),
                "{name}: a body line says more than which block it is: {line}"
            );
            assert_eq!(
                comment.split_whitespace().count(),
                3,
                "{name}: the id is the whole comment: {line}"
            );
        }
        for token in [
            " t: ",
            " prev: ",
            " from: ",
            " star",
            " done",
            " collapsed",
            " ordered: ",
            "<!-- ya:",
        ] {
            assert!(
                !body.contains(token),
                "{name}: `{token}` is still in the body"
            );
        }
        assert!(
            footer.trim_end().ends_with("-->"),
            "{name}: the footer is not closed"
        );
    }
}
