interface PerformanceStats {
  readonly medianMs: number;
  readonly samplesMs: readonly number[];
}

interface PairedPerformanceStats {
  readonly workload: PerformanceStats;
  readonly calibration: PerformanceStats;
  readonly normalized: PerformanceStats;
}

interface PairedBatchSample {
  readonly workloadMs: number;
  readonly calibrationMs: number;
}

interface TimedWorkloadSample {
  readonly elapsedMs: number;
  readonly output: unknown;
}

interface RepresentativePairedSample extends PairedBatchSample {
  readonly normalizedRatio: number;
}

interface PreparedWorkload {
  readonly run: () => unknown;
  readonly expected: unknown;
}

interface RecordedBaseline {
  readonly pairedRatioMedian: number;
}

interface PerformanceCase {
  readonly label: string;
  readonly scope: string;
  readonly nodeCount: 1_000 | 10_000;
  readonly operationsPerSample: number;
  readonly recordedBaseline: RecordedBaseline;
  readonly prepare: (nodeCount: number) => PreparedWorkload;
}

function summarizeSamples(samplesMs: readonly number[]): PerformanceStats {
  const sortedSamples = [...samplesMs].sort((left, right) => left - right);
  return {
    medianMs: sortedSamples[Math.floor(sortedSamples.length / 2)]!,
    samplesMs
  };
}

function measurePerOperationAverage(
  workload: PreparedWorkload,
  operationsPerSample: number
): TimedWorkloadSample {
  const startedAt = performance.now();
  let output: unknown;
  for (let operation = 0; operation < operationsPerSample; operation += 1) {
    output = workload.run();
  }
  const elapsedMs = (performance.now() - startedAt) / operationsPerSample;
  return { elapsedMs, output };
}

function representativeSample(samplesMs: readonly number[]): number {
  return summarizeSamples(samplesMs).medianMs;
}

function representativePairedSample(
  samples: readonly PairedBatchSample[]
): RepresentativePairedSample {
  return {
    workloadMs: representativeSample(
      samples.map(({ workloadMs }) => workloadMs)
    ),
    calibrationMs: representativeSample(
      samples.map(({ calibrationMs }) => calibrationMs)
    ),
    normalizedRatio: representativeSample(
      samples.map(({ workloadMs, calibrationMs }) =>
        workloadMs / calibrationMs
      )
    )
  };
}

function measurePairedBatch(
  calibration: PreparedWorkload,
  workload: PreparedWorkload,
  operationsPerSample: number,
  workloadFirst: boolean
): PairedBatchSample {
  let workloadSample: TimedWorkloadSample;
  let calibrationSample: TimedWorkloadSample;
  if (workloadFirst) {
    workloadSample = measurePerOperationAverage(
      workload,
      operationsPerSample
    );
    calibrationSample = measurePerOperationAverage(calibration, 1);
  } else {
    calibrationSample = measurePerOperationAverage(calibration, 1);
    workloadSample = measurePerOperationAverage(workload, operationsPerSample);
  }

  expect(workloadSample.output).toEqual(workload.expected);
  expect(calibrationSample.output).toEqual(calibration.expected);
  return {
    workloadMs: workloadSample.elapsedMs,
    calibrationMs: calibrationSample.elapsedMs
  };
}

function measurePairedWorkload(
  workload: PreparedWorkload,
  operationsPerSample = 1
): PairedPerformanceStats {
  const calibration = prepareCalibration();
  for (let index = 0; index < WARMUP_PAIR_COUNT; index += 1) {
    measurePairedBatch(
      calibration,
      workload,
      operationsPerSample,
      index % 2 === 1
    );
  }

  const workloadSamplesMs: number[] = [];
  const calibrationSamplesMs: number[] = [];
  const normalizedSamples: number[] = [];
  for (let index = 0; index < MEASURED_PAIR_COUNT; index += 1) {
    const sample = measurePairedBatch(
      calibration,
      workload,
      operationsPerSample,
      (WARMUP_PAIR_COUNT + index) % 2 === 1
    );
    workloadSamplesMs.push(sample.workloadMs);
    calibrationSamplesMs.push(sample.calibrationMs);
    normalizedSamples.push(sample.workloadMs / sample.calibrationMs);
  }

  return {
    workload: summarizeSamples(workloadSamplesMs),
    calibration: summarizeSamples(calibrationSamplesMs),
    normalized: summarizeSamples(normalizedSamples)
  };
}

function recordedBaseline(pairedRatioMedian: number): RecordedBaseline {
  return { pairedRatioMedian };
}

function normalizedRegressionRatio(
  currentPairedRatioMedian: number,
  baseline: RecordedBaseline
): number {
  return currentPairedRatioMedian / baseline.pairedRatioMedian;
}

function calibrationChecksum(iterations: number): number {
  const blockSize = 1024;
  const fullBlocks = Math.floor(iterations / blockSize);
  const remainder = iterations % blockSize;
  return (
    fullBlocks * ((blockSize - 1) * blockSize / 2) +
    (remainder - 1) * remainder / 2
  );
}

function prepareCalibration(): PreparedWorkload {
  return {
    run: () => {
      let checksum = 0;
      for (let index = 0; index < CALIBRATION_ITERATIONS; index += 1) {
        checksum += index & 1023;
      }
      return checksum;
    },
    expected: calibrationChecksum(CALIBRATION_ITERATIONS)
  };
}

function countResidue(total: number, residue: number, divisor: number): number {
  return total <= residue ? 0 : Math.floor((total - 1 - residue) / divisor) + 1;
}

