function prepareMixedImageOutlineProjectionBookkeeping(
  nodeCount: number
): PreparedWorkload {
  const attachmentsByNodeId: Record<string, NoteAttachment[]> = {};
  const nodes = treeNodes(nodeCount).map((node, index) => {
    if (index >= MIXED_IMAGE_ATTACHMENT_COUNT) return node;

    const attachment = noteAttachment(index, node.id);
    attachmentsByNodeId[node.id] = [attachment];
    if (index % 2 === 0) return node;

    return {
      ...node,
      nodeKind: "image" as const,
      title: attachment.originalName,
      note: `Image description ${index}`
    };
  });
  const workspace = normalizeWorkspace({ nodes, attachmentsByNodeId });

  return {
    run: () => {
      const rows = flattenVisibleOutlineRows(workspace, null);
      const residentAttachmentIds: string[] = [];
      let createdObjectUrlCount = 0;
      let maxResidentObjectUrlCount = 0;
      let revokedObjectUrlCount = 0;
      let legacyAttachmentCount = 0;
      let imageNodeAttachmentCount = 0;
      let imageByteSizeChecksum = 0;

      for (const row of rows) {
        const node = workspace.nodesById[row.id];
        const attachments = workspace.attachmentsByNodeId[row.id] ?? [];
        if (!node || attachments.length === 0) continue;

        if (node.nodeKind === "image") {
          imageNodeAttachmentCount += attachments.length;
        } else {
          legacyAttachmentCount += attachments.length;
        }

        for (const attachment of attachments) {
          imageByteSizeChecksum += attachment.byteSize;
          const residentIndex = residentAttachmentIds.indexOf(attachment.id);
          if (residentIndex >= 0) {
            residentAttachmentIds.splice(residentIndex, 1);
          } else {
            createdObjectUrlCount += 1;
          }
          residentAttachmentIds.push(attachment.id);
          if (residentAttachmentIds.length > MIXED_IMAGE_RESIDENCY_LIMIT) {
            residentAttachmentIds.shift();
            revokedObjectUrlCount += 1;
          }
          maxResidentObjectUrlCount = Math.max(
            maxResidentObjectUrlCount,
            residentAttachmentIds.length
          );
        }
      }

      const residentCountBeforeRelease = residentAttachmentIds.length;
      revokedObjectUrlCount += residentAttachmentIds.length;
      residentAttachmentIds.length = 0;

      return {
        rowCount: rows.length,
        firstId: rows[0]?.id ?? null,
        legacyAttachmentCount,
        imageNodeAttachmentCount,
        createdObjectUrlCount,
        maxResidentObjectUrlCount,
        residentCountBeforeRelease,
        residentCountAfterRelease: residentAttachmentIds.length,
        revokedObjectUrlCount,
        imageByteSizeChecksum
      };
    },
    expected: {
      rowCount: nodeCount,
      firstId: "node-0",
      legacyAttachmentCount: MIXED_IMAGE_ATTACHMENT_COUNT / 2,
      imageNodeAttachmentCount: MIXED_IMAGE_ATTACHMENT_COUNT / 2,
      createdObjectUrlCount: MIXED_IMAGE_ATTACHMENT_COUNT,
      maxResidentObjectUrlCount: MIXED_IMAGE_RESIDENCY_LIMIT,
      residentCountBeforeRelease: MIXED_IMAGE_RESIDENCY_LIMIT,
      residentCountAfterRelease: 0,
      revokedObjectUrlCount: MIXED_IMAGE_ATTACHMENT_COUNT,
      imageByteSizeChecksum: MIXED_IMAGE_ATTACHMENT_COUNT * 4
    }
  };
}

