performanceSuite("notes expansion frontend performance", () => {
  beforeAll(() => {
    console.info(
      "[notes-perf] invocation: NOTES_PERF=1 npm test -- " +
        "src/features/notes/notesExpansion.performance.test.ts " +
        "--pool=threads --maxWorkers=1 --no-file-parallelism"
    );
    console.info(
      `[notes-perf] recorded=${JSON.stringify(recordedEnvironment)}`
    );
  });

  it("declares the exact reviewed workload-size matrix", () => {
    const sizesByLabel = new Map<string, number[]>();
    for (const performanceCase of cases) {
      const sizes = sizesByLabel.get(performanceCase.label) ?? [];
      sizes.push(performanceCase.nodeCount);
      sizesByLabel.set(performanceCase.label, sizes);
    }

    expect(Object.fromEntries(sizesByLabel)).toEqual({
      "active workspace load": [1_000, 10_000],
      tokenization: [1_000, 10_000],
      "visible-row derivation": [1_000, 10_000],
      "mixed image outline projection bookkeeping": [10_000],
      "tag query parser preparation": [1_000, 10_000],
      "date token parse + index preparation": [1_000, 10_000],
      "Archive/unarchive lifecycle preparation": [1_000, 10_000],
      "mutation + Undo workspace settlement": [1_000, 10_000],
      "local history eviction": [1_000, 10_000]
    });
  });

  it("scopes the mixed image projection benchmark as synthetic bookkeeping", () => {
    const mixedImageCase = cases.find(
      ({ label }) => label === "mixed image outline projection bookkeeping"
    );

    expect(mixedImageCase?.scope).toBe(projectionBenchmarkScope);
    expect(mixedImageCase?.scope).toContain(
      "not production rendering or residency"
    );
    expect(
      cases.some(({ label }) => /mixed image.*residency/iu.test(label))
    ).toBe(false);
  });

  it("labels backend-owned search work as frontend preparation only", () => {
    expect(cases.map(({ label }) => label)).toContain(
      "tag query parser preparation"
    );
    expect(cases.map(({ label }) => label)).toContain(
      "date token parse + index preparation"
    );
    expect(cases.some(({ label }) => /tag.*match|production search/iu.test(label)))
      .toBe(false);
    expect(
      cases
        .filter(({ label }) => /tag|date/iu.test(label))
        .every(({ scope }) => scope === preparationScope)
    ).toBe(true);
  });

  it("stores only the recorded median of three pair ratios", () => {
    for (const performanceCase of cases) {
      expect(Object.keys(performanceCase.recordedBaseline)).toEqual([
        "pairedRatioMedian"
      ]);
      expect(
        performanceCase.recordedBaseline.pairedRatioMedian
      ).toBeGreaterThan(0);
    }
  });

  it("records like-for-like paired normalization without changing the gate", () => {
    expect(recordedEnvironment.sampling).toContain("3 measured paired batches");
    expect(recordedEnvironment.sampling).toContain("per case");
    expect(recordedEnvironment.sampling).toContain("median of 3 pair ratios");
    expect(recordedEnvironment.sampling).toContain(
      "outputs validated only after both timing windows"
    );
    expect(recordedEnvironment.sampling).not.toContain("p95");
    expect(WARMUP_PAIR_COUNT).toBe(3);
    expect(MEASURED_PAIR_COUNT).toBe(3);
    expect(REGRESSION_LIMIT).toBe(1.2);
  });

  it("rejects one localized scheduler spike without hiding a sustained slowdown", () => {
    const baseline = recordedBaseline(1);
    const schedulerSpike = representativePairedSample([
      { workloadMs: 1, calibrationMs: 1 },
      { workloadMs: 9, calibrationMs: 1 },
      { workloadMs: 1.01, calibrationMs: 1 }
    ]);
    const sustainedSlowdown = representativePairedSample([
      { workloadMs: 1.21, calibrationMs: 1 },
      { workloadMs: 1.22, calibrationMs: 1 },
      { workloadMs: 1.23, calibrationMs: 1 }
    ]);

    expect(schedulerSpike.normalizedRatio).toBe(1.01);
    expect(
      normalizedRegressionRatio(schedulerSpike.normalizedRatio, baseline)
    ).toBeLessThanOrEqual(REGRESSION_LIMIT);
    expect(sustainedSlowdown.normalizedRatio).toBe(1.22);
    expect(
      normalizedRegressionRatio(sustainedSlowdown.normalizedRatio, baseline)
    ).toBeGreaterThan(REGRESSION_LIMIT);
  });

  it("normalizes a common two-times host slowdown within each pair", () => {
    const baseline = recordedBaseline(1);
    const current = representativePairedSample([
      { workloadMs: 2, calibrationMs: 2 },
      { workloadMs: 2.02, calibrationMs: 2 },
      { workloadMs: 2.04, calibrationMs: 2 }
    ]);

    expect(current.normalizedRatio).toBeCloseTo(1.01, 10);
    expect(normalizedRegressionRatio(current.normalizedRatio, baseline)).toBeCloseTo(
      1.01,
      10
    );
  });

  it.each([
    { workloadFirst: true, expectedRuns: ["run:workload", "run:calibration"] },
    { workloadFirst: false, expectedRuns: ["run:calibration", "run:workload"] }
  ])(
    "validates both outputs after adjacent timing windows when workloadFirst=$workloadFirst",
    ({ workloadFirst, expectedRuns }) => {
      const events: string[] = [];
      const observableWorkload = (label: string): PreparedWorkload => ({
        run: () => {
          events.push(`run:${label}`);
          return Object.defineProperty({}, "value", {
            enumerable: true,
            get: () => {
              events.push(`validate:${label}`);
              return label;
            }
          });
        },
        expected: { value: label }
      });

      measurePairedBatch(
        observableWorkload("calibration"),
        observableWorkload("workload"),
        1,
        workloadFirst
      );

      const firstValidationIndex = events.findIndex((event) =>
        event.startsWith("validate:")
      );
      expect(events.slice(0, firstValidationIndex)).toEqual(expectedRuns);
    }
  );

  it("runs pure timing in Node without a DOM environment", () => {
    expect(process.release.name).toBe("node");
    expect(typeof document).toBe("undefined");
  });

  it.each(cases)(
    "$label: $nodeCount nodes; paired-ratio median <= recorded +20%",
    { timeout: 120_000 },
    ({
      label,
      scope,
      nodeCount,
      operationsPerSample,
      recordedBaseline: baseline,
      prepare
    }) => {
      const pairedStats = measurePairedWorkload(
        prepare(nodeCount),
        operationsPerSample
      );
      const stats = pairedStats.workload;
      const localCalibration = pairedStats.calibration;
      const pairedRatios = pairedStats.normalized;
      const ratio = normalizedRegressionRatio(
        pairedRatios.medianMs,
        baseline
      );

      expect(stats.samplesMs).toHaveLength(MEASURED_PAIR_COUNT);
      expect(stats.samplesMs.every(Number.isFinite)).toBe(true);
      expect(localCalibration.samplesMs).toHaveLength(MEASURED_PAIR_COUNT);
      expect(localCalibration.samplesMs.every(Number.isFinite)).toBe(true);
      expect(pairedRatios.samplesMs).toHaveLength(MEASURED_PAIR_COUNT);
      expect(pairedRatios.samplesMs.every(Number.isFinite)).toBe(true);
      console.info(
        `[notes-perf] ${label}; scope=${scope}; nodes=${nodeCount}; ` +
          `pairedWarmups=${WARMUP_PAIR_COUNT}; ` +
          `measuredPairs=${MEASURED_PAIR_COUNT}; ` +
          `operationsPerSample=${operationsPerSample}; ` +
          `workloadMedian=${stats.medianMs.toFixed(2)}ms; ` +
          `calibrationMedian=${localCalibration.medianMs.toFixed(
            2
          )}ms; pairedRatioMedian=${pairedRatios.medianMs.toFixed(6)}; ` +
          `recordedPairedRatioMedian=${baseline.pairedRatioMedian.toFixed(
            6
          )}; ` +
          `normalizedRatio=${ratio.toFixed(3)}; gate=${REGRESSION_LIMIT.toFixed(
            2
          )}`
      );
      expect(ratio).toBeLessThanOrEqual(REGRESSION_LIMIT);
    }
  );
});
